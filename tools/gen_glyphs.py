"""Extract the Bravura (SMuFL) glyph outlines the app needs into js/glyphs.js.

Bravura is (c) Steinberg Media Technologies GmbH, licensed under the SIL Open Font
License 1.1. The outlines are read from the copy bundled with the `verovio` package
(pip install verovio). Run from the webapp folder: python3 tools/gen_glyphs.py
"""
import os
import re
import verovio

src = os.path.join(os.path.dirname(verovio.__file__), "data", "Bravura")


def outline(code):
    with open(os.path.join(src, code + ".xml"), encoding="utf-8") as f:
        return " ".join(re.search(r'\sd="([^"]*)"', f.read()).group(1).split())


glyphs = {"gclef": outline("E050"), "gclef8vb": outline("E052"), "gclef8va": outline("E053"), "fclef": outline("E062"), "cclef": outline("E05C"),
          "sharp": outline("E262"), "flat": outline("E260")}
lines = [
    "/* Bravura music glyph outlines (SMuFL), font units: 1 staff space = 250.",
    "   Bravura (c) Steinberg Media Technologies GmbH, SIL Open Font License 1.1.",
    "   Generated by tools/gen_glyphs.py - do not edit by hand. */",
    "var Glyphs = {",
]
for i, (k, v) in enumerate(glyphs.items()):
    lines.append(f'  {k}: "{v}"' + ("," if i < len(glyphs) - 1 else ""))
lines += ["};", "if (typeof module !== 'undefined' && module.exports) { module.exports = Glyphs; }", ""]
with open(os.path.join("js", "glyphs.js"), "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
print({k: len(v) for k, v in glyphs.items()})
